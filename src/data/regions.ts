/** 短名 → 省，用于反查与校验 */
const PROVINCE_BY_SHORT = new Map(PROVINCES.map((p) => [p.short, p]));

export function findProvince(shortOrFull: string): Province | null {
  const key = normalizeProvince(shortOrFull);
  if (!key) return null;
  return PROVINCE_BY_SHORT.get(key) ?? null;
}

/**
 * 省名归一化：去掉「省 / 市 / 自治区 / 特别行政区」等后缀，以及自治区中的民族名
 * 「内蒙古自治区」→「内蒙古」、「广西壮族自治区」→「广西」、「香港特别行政区」→「香港」
 * 这是分布文本比对的唯一入口
 */
export function normalizeProvince(name: string): string {
  return String(name ?? "")
    .trim()
    .replace(/维吾尔自治区|壮族自治区|回族自治区|自治区|特别行政区|省|市/g, "")
    .trim();
}

/** 全国性分布表述：出现即视为「本省有分布」 */
const NATIONAL_KEYWORDS = [
  "国内各省",
  "各省栽培",
  "全国各地",
  "全国广布",
  "各地栽培",
];

/**
 * 判断 CVH 的 distribution_c 文本是否包含指定省份
 * 分布文本以「、」分隔（如「浙江、湖北、重庆、贵州、国内各省栽培」），
 * 也兼容逗号 / 分号 / 斜杠等写法
 */
export function matchesProvince(
  distribution: string,
  provinceShort: string
): boolean {
  const dist = String(distribution ?? "").trim();
  const target = normalizeProvince(provinceShort);
  if (!dist || !target) return false;

  if (NATIONAL_KEYWORDS.some((k) => dist.includes(k))) return true;

  return dist
    .split(/[、,，;；/|\s]+/)
    .map((token) => normalizeProvince(token))
    .some((token) => token === target);
}
